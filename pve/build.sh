#!/usr/bin/env bash
# Builds pve/install.sh by concatenating pve/install-parts/*.sh in name order.
#
# install.sh stays ONE self-contained file (committed, shipped in the release
# bundle) because it is run as `bash -c "$(curl …/pve/install.sh)"` and can't
# source anything next to it. Edit the parts, never install.sh.
#
# Files in install-parts/files/{bin,systemd,udev}/ (helper scripts, udev rules, systemd units; they may
# hold @VAR@ placeholders, see render_file() in 20-helpers.sh) are inlined as heredocs
# into get_file(), so they stay real files in the repo but ship inside install.sh.
#
#   pve/build.sh            regenerate pve/install.sh
#   pve/build.sh --check    fail if pve/install.sh is stale or has syntax errors (CI)
set -euo pipefail

cd "$(dirname "${BASH_SOURCE[0]}")"
OUT=install.sh

# get_file <dir/name>: prints install-parts/files/<dir/name>
render_embedded() {
  local f name tag=CDH_EMBEDDED_EOF
  echo "# ════ install-parts/files/* (inlined by build.sh) ════"
  echo "get_file() {"
  echo '  case $1 in'
  for f in $(find install-parts/files -type f | sort); do
    name=${f#install-parts/files/}
    if grep -qx "$tag" "$f"; then echo "build.sh: $f contains the line $tag" >&2; exit 1; fi
    echo "    $name)"
    echo "      cat <<'$tag'"
    cat "$f"
    echo "$tag"
    echo "      ;;"
  done
  echo '    *) echo "get_file: no file $1" >&2; return 1 ;;'
  echo "  esac"
  echo "}"
}

render() {
  local f first=1
  for f in install-parts/*.sh; do
    if ((first)); then   # 00-header.sh: shebang first, then the generated-file banner
      head -n1 "$f"
      echo "# GENERATED by pve/build.sh from pve/install-parts/*.sh: do not edit, edit the parts and rebuild."
      tail -n +2 "$f"
      echo
      render_embedded
      first=0
    else
      echo
      echo "# ════ ${f} ════"
      cat "$f"
    fi
  done
}

tmp=$(mktemp)
trap 'rm -f "$tmp"' EXIT
render >"$tmp"
bash -n "$tmp" || { echo "build.sh: syntax error in the merged script" >&2; exit 1; }

if [[ ${1:-} == --check ]]; then
  if ! cmp -s "$tmp" "$OUT"; then
    echo "pve/$OUT is out of date: run pve/build.sh and commit the result" >&2
    exit 1
  fi
  echo "pve/$OUT is up to date"
else
  cat "$tmp" >"$OUT"
  chmod 0755 "$OUT"
  echo "built pve/$OUT from $(ls install-parts/*.sh | wc -l) parts"
fi
