/* ── Отрисовка символа ── */
static void draw_char(uint32_t *data, int stride, int x, int y, char c, uint32_t color) {
    if (c < 32 || c > 126) c = '?';
    
    // Переводим в индекс в атласе (пробел = 0)
    int idx = (int)c - 32;
    if (idx >= 95) idx = 31; // '?'

    for (int j = 0; j < 16; j++) {
        uint8_t row = font8x16[idx][j];
        for (int i = 0; i < 8; i++) {
            // Рисуем бит (msb first)
            if (row & (0x80 >> i)) {
                data[(y + j) * stride + (x + i)] = color;
            }
        }
    }
}

static void draw_text(uint32_t *data, int stride, int x, int y, const char *text, uint32_t color) {
    int cur_x = x;
    while (*text) {
        draw_char(data, stride, cur_x, y, *text, color);
        cur_x += 8;
        text++;
    }
}

void cd_render_debug_overlay(struct cd_server *server, struct wlr_render_pass *pass) {
    if (!server->hud) return;

    // Параметры оверлея
    int width = 320;
    int height = 130;
    int stride = width;
    uint32_t *pixels = (uint32_t*)calloc(width * height, sizeof(uint32_t));

    // Фон (полупрозрачный черный)
    for (int i = 0; i < width * height; i++) pixels[i] = 0x88000000;

    char buf[128];
    // Строка 1: FPS + Target
    int target_hz = server->cur_refresh / 1000;
    snprintf(buf, sizeof(buf), "FPS: %.1f / %dHZ", server->hud_fps, target_hz);
    draw_text(pixels, stride, 10, 5, buf, 0xFF00FF00);

    // Строка 2: KWin commit rate
    snprintf(buf, sizeof(buf), "KWIN: %.1F C/S", server->hud_kwin_commit_rate);
    draw_text(pixels, stride, 10, 23, buf, 0xFF88FF88);

    // Строка 3: Mouse deltas
    snprintf(buf, sizeof(buf), "DXY: %.1F  %.1F", server->hud_mouse_dx, server->hud_mouse_dy);
    draw_text(pixels, stride, 10, 41, buf, 0xFF00FFFF);

    // Строка 4: Constraints Counter
    snprintf(buf, sizeof(buf), "COUNT NEW POINTER CONSTRAINT: %u", server->hud_constraint_count);
    draw_text(pixels, stride, 10, 59, buf, server->hud_constraint_count > 0 ? 0xFFFF8800 : 0xFF888888);

    // Строка 5: Activated State
    bool activated = server->has_active_constraint;
    snprintf(buf, sizeof(buf), "SYSTEM MODE: %s", activated ? "LOCKED" : "FREE");
    draw_text(pixels, stride, 10, 77, buf, activated ? 0xFFFF4444 : 0xFF88FF88);

    // Строка 6: WATCHDOG WL SURFACE FRAME
    snprintf(buf, sizeof(buf), "WATCHDOG WL SURFACE FRAME: %u", server->hud_watchdog_commits);
    draw_text(pixels, stride, 10, 95, buf, 0xFFFFFFFF);


    // Создаем текстуру из пикселей
    // Внимание: в wlroots 0.18+ отрисовка идет через render_pass.
    // Нам нужно создать wlr_texture и отрисовать её.
    
    struct wlr_texture *texture = wlr_texture_from_pixels(
        server->renderer,
        DRM_FORMAT_ARGB8888,
        width * 4,
        width,
        height,
        pixels
    );

    if (texture) {
        struct wlr_render_texture_options opts = {};
        opts.texture = texture;
        opts.dst_box.x = 20;
        opts.dst_box.y = 20;
        opts.dst_box.width = width;
        opts.dst_box.height = height;
        wlr_render_pass_add_texture(pass, &opts);
        
        wlr_texture_destroy(texture);
    }

    free(pixels);
}
